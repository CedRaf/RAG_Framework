import os
import json
from pathlib import Path
from pymilvus import MilvusClient, DataType, Function, FunctionType, connections
from dotenv import load_dotenv

load_dotenv()

client = MilvusClient(uri="http://localhost:19530", token="root:Milvus")
connections.connect(host="localhost", port="19530")

COLLECTION_NAME = "flattened_10k_hybrid"
EMBEDDING_DIM = 1024
MAX_TEXT_LENGTH = 1000


def create_flattened_collection():
    """Create Milvus collection for flattened 10-K documents with hybrid search"""
    if COLLECTION_NAME in client.list_collections():
        client.drop_collection(COLLECTION_NAME)
        print(f"Dropped existing collection: {COLLECTION_NAME}")
    
    schema = client.create_schema()
    
    # Primary and core fields
    schema.add_field("id", DataType.VARCHAR, max_length=500, is_primary=True)
    schema.add_field("text", DataType.VARCHAR, max_length=MAX_TEXT_LENGTH, enable_analyzer=True)
    
    # Vector fields
    schema.add_field("dense_vector", DataType.FLOAT_VECTOR, dim=EMBEDDING_DIM)
    schema.add_field("sparse_vector", DataType.SPARSE_FLOAT_VECTOR)
    
    # Metadata fields from flattened JSON
    schema.add_field("ticker", DataType.VARCHAR, max_length=32)
    schema.add_field("company_name", DataType.VARCHAR, max_length=200)
    schema.add_field("fiscal_year", DataType.VARCHAR, max_length=4)
    schema.add_field("fiscal_date", DataType.VARCHAR, max_length=20)
    schema.add_field("line_item", DataType.VARCHAR, max_length=500)
    schema.add_field("concept", DataType.VARCHAR, max_length=200)
    schema.add_field("value", DataType.DOUBLE)
    schema.add_field("value_formatted", DataType.VARCHAR, max_length=100)
    schema.add_field("table_type", DataType.VARCHAR, max_length=50)
    schema.add_field("document_type", DataType.VARCHAR, max_length=20)
    
    # BM25 function for sparse vectors (auto-generated by Milvus)
    bm25_function = Function(
        name="text_bm25_emb",
        input_field_names=["text"],
        output_field_names=["sparse_vector"],
        function_type=FunctionType.BM25,
    )
    schema.add_function(bm25_function)
    
    # Create indexes
    index_params = client.prepare_index_params()
    
    # Dense vector index (HNSW for fast similarity search)
    index_params.add_index(
        field_name="dense_vector",
        index_type="HNSW",
        metric_type="COSINE",
        params={"M": 64, "efConstruction": 512}
    )
    
    # Sparse vector index (BM25 for keyword matching)
    index_params.add_index(
        field_name="sparse_vector",
        index_type="SPARSE_INVERTED_INDEX",
        metric_type="BM25",
        params={
            "inverted_index_algo": "DAAT_MAXSCORE",
            "bm25_k1": 1.6,
            "bm25_b": 0.7
        }
    )
    
    client.create_collection(
        collection_name=COLLECTION_NAME,
        schema=schema,
        index_params=index_params
    )
    
    print(f"✓ Created collection: {COLLECTION_NAME}")
    return COLLECTION_NAME


def load_embedded_json_files(base_dir="edgar-tools/embeddings"):
    """Load all JSON files with pre-generated embeddings"""
    all_records = []
    
    if not os.path.exists(base_dir):
        print(f"❌ Directory not found: {base_dir}")
        print(f"⚠ Please run generate_embeddings.py first to create embeddings")
        return all_records
    
    print(f"Loading embedded JSON files from: {base_dir}")
    
    # Walk through all subdirectories
    for root, dirs, files in os.walk(base_dir):
        for filename in files:
            if filename.endswith("_flattened.json"):
                file_path = os.path.join(root, filename)
                
                try:
                    with open(file_path, "r", encoding="utf-8") as f:
                        records = json.load(f)
                        
                    if isinstance(records, list):
                        # Verify embeddings exist
                        if records and "dense_embedding" not in records[0]:
                            print(f"  ⚠ No embeddings found in {filename}, skipping")
                            continue
                        
                        all_records.extend(records)
                        print(f"  ✓ Loaded {len(records)} records from {filename}")
                    else:
                        print(f"  ⚠ Unexpected format in {filename}")
                        
                except json.JSONDecodeError as e:
                    print(f"  ❌ Error decoding {filename}: {str(e)}")
                except Exception as e:
                    print(f"  ❌ Error reading {filename}: {str(e)}")
    
    print(f"\n✓ Total records loaded: {len(all_records)}")
    return all_records


def insert_embedded_data():
    """Load embedded JSON files and insert into Milvus"""
    
    # Load all records with pre-generated embeddings
    records = load_embedded_json_files()
    
    if not records:
        print("❌ No records to insert")
        print("⚠ Run generate_embeddings.py first to generate embeddings")
        return
    
    # Prepare data for insertion
    print(f"\n{'='*80}")
    print("Preparing data for insertion...")
    print(f"{'='*80}")
    
    milvus_data = []
    
    for i, record in enumerate(records):
        # Verify embedding exists
        if "dense_embedding" not in record:
            print(f"  ⚠ Skipping record {i}: No embedding found")
            continue
        
        # Handle missing values
        value = record.get("value")
        if value is None or not isinstance(value, (int, float)):
            value = 0.0
        
        milvus_entry = {
            "id": record.get("id", f"unknown_{i}"),
            "text": record.get("text", ""),
            "dense_vector": record["dense_embedding"],  # Pre-generated embedding
            "ticker": record.get("ticker", "UNKNOWN"),
            "company_name": record.get("company_name", "Unknown Company"),
            "fiscal_year": record.get("fiscal_year", "0000"),
            "fiscal_date": record.get("fiscal_date", ""),
            "line_item": record.get("line_item", ""),
            "concept": record.get("concept", ""),
            "value": float(value),
            "value_formatted": record.get("value_formatted", ""),
            "table_type": record.get("table_type", ""),
            "document_type": record.get("document_type", "10-K")
        }
        
        milvus_data.append(milvus_entry)
    
    print(f"✓ Prepared {len(milvus_data)} entries for insertion")
    
    # Insert in batches (BM25 sparse vectors auto-generated by Milvus)
    print(f"\n{'='*80}")
    print("Inserting data into Milvus...")
    print(f"{'='*80}")
    
    batch_size = 1000
    for i in range(0, len(milvus_data), batch_size):
        batch = milvus_data[i:i+batch_size]
        client.insert(COLLECTION_NAME, batch)
        print(f"  ✓ Inserted batch {i//batch_size + 1}/{(len(milvus_data)-1)//batch_size + 1} ({len(batch)} records)")
    
    print(f"\n✓ Data insertion complete!")
    
    # Print summary statistics
    print(f"\n{'='*80}")
    print("SUMMARY")
    print(f"{'='*80}")
    
    # Count by table type
    table_types = {}
    tickers = set()
    fiscal_years = set()
    
    for record in records:
        table_type = record.get("table_type", "Unknown")
        table_types[table_type] = table_types.get(table_type, 0) + 1
        tickers.add(record.get("ticker", "UNKNOWN"))
        fiscal_years.add(record.get("fiscal_year", "0000"))
    
    print(f"\nTotal records inserted: {len(milvus_data)}")
    print(f"Unique companies: {len(tickers)}")
    print(f"Fiscal years covered: {sorted(fiscal_years)}")
    print(f"\nRecords by table type:")
    for table_type, count in sorted(table_types.items()):
        print(f"  {table_type}: {count}")


def setup_milvus_flattened():
    """Main setup function"""
    print("="*80)
    print("MILVUS FLATTENED 10-K SETUP")
    print("="*80)
    print()
    
    print("Step 1: Creating Milvus collection...")
    create_flattened_collection()
    print()
    
    print("Step 2: Loading and inserting embedded data...")
    insert_embedded_data()
    print()
    
    print("="*80)
    print("✓ SETUP COMPLETE!")
    print("="*80)
    print(f"\nCollection '{COLLECTION_NAME}' is ready for hybrid search")
    print("You can now query using:")
    print("  - Dense vector search (semantic similarity)")
    print("  - Sparse vector search (BM25 keyword matching) - AUTO-GENERATED")
    print("  - Metadata filters (ticker, fiscal_year, table_type, etc.)")
    print()


if __name__ == "__main__":
    setup_milvus_flattened()